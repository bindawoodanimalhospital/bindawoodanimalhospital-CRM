import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { InfoGrid, PrintShell, type ClinicProfile } from "@/components/print/print-shell";
import { requireStaff } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { getSetting } from "@/lib/queries";
import { formatDate, formatDateTime, formatPKR } from "@/lib/format";
import { formatPhone } from "@/lib/phone";
import { withContact } from "@/lib/contacts";

export const metadata: Metadata = { title: "Receipt" };

export default async function ReceiptPrint({ params }: PageProps<"/print/receipt/[id]">) {
  const me = await requireStaff();
  if (!me.can("billing.view") && !me.can("pos.use")) notFound();
  const { id } = await params;
  const supabase = await createClient();
  const [{ data: p }, clinic, { data: methods }] = await Promise.all([
    supabase.from("payments").select("code, kind, amount, method, reference, notes, received_at, receiver:received_by(full_name), customers(full_name, customer_contacts(phone, whatsapp)), payment_allocations(amount, invoices(number, balance, walk_in_name, status))").eq("id", id).maybeSingle(),
    getSetting<ClinicProfile>("clinic.profile"),
    supabase.from("payment_methods").select("key, label"),
  ]);
  if (!p) notFound();
  const customer = withContact(p.customers as unknown as { full_name: string } | null);
  const allocs = (p.payment_allocations ?? []) as unknown as { amount: number; invoices: { number: string; balance: number; walk_in_name: string | null; status: string } }[];
  const refund = p.kind === "refund";
  const receiver = (p.receiver as unknown as { full_name: string } | null)?.full_name ?? null;
  const walkIn = allocs.map((a) => a.invoices.walk_in_name).find(Boolean);
  const who = customer ? [customer.full_name, formatPhone(customer.phone)].filter(Boolean).join(" · ") : walkIn ? `${walkIn} (walk-in)` : "Walk-in";
  const stillOwed = refund ? [] : allocs.filter((a) => Number(a.invoices.balance) > 0 && a.invoices.status !== "void");
  const used = allocs.reduce((s, a) => s + Math.abs(Number(a.amount)), 0);
  const label = methods?.find((m) => m.key === p.method)?.label ?? p.method;

  return (
    <PrintShell clinic={clinic ?? {}} title={refund ? "Refund receipt" : "Payment receipt"} footer={<>Generated by the Bin Dawood Animal Hospital system.</>}>
      <div className="flex justify-between text-xs text-muted-foreground"><span>No. {p.code}</span><span>{formatDateTime(p.received_at)}</span></div>
      <div className="mt-2"><InfoGrid rows={[[refund ? "Refunded to" : "Received from", who], ["Method", `${label}${p.reference ? ` · ${p.reference}` : ""}`], [refund ? "Refunded by" : "Received by", receiver]]} /></div>
      <p className="mt-6 text-center text-3xl font-bold">{formatPKR(p.amount)}</p>
      {allocs.length > 0 && (
        <div className="mt-6 text-sm">
          <p className="font-semibold text-muted-foreground uppercase">{refund ? "Refunded on" : "Paid towards"}</p>
          {allocs.map((a, i) => <p key={i}>Bill {a.invoices.number}: {formatPKR(Math.abs(Number(a.amount)))}</p>)}
          {p.kind === "payment" && Number(p.amount) - used > 0 && <p>Kept as advance: {formatPKR(Number(p.amount) - used)}</p>}
        </div>
      )}
      {stillOwed.length > 0 && (
        <p className="mt-4 rounded-xl px-3 py-2 text-sm font-semibold ring-1 ring-brand">
          Still to pay (as of {formatDate(new Date())}): {stillOwed.map((a) => `${formatPKR(Number(a.invoices.balance))} on bill ${a.invoices.number}`).join(" · ")}
        </p>
      )}
      {p.notes && <p className="mt-4 text-sm">{p.notes}</p>}
      <div className="mt-16 flex justify-end"><div className="w-56 border-t border-ink pt-1 text-center text-xs">{refund ? "Customer's signature" : "Signature"}</div></div>
    </PrintShell>
  );
}
